// A name between colons with no letter or digit against either side of it,
// so 10:30:45 and a ratio of 1:100:1 stay as they were typed. Any case, since
// a phone capitalises the first word it sees.
const NAME = /(?<![\p{L}\p{N}]):([a-z0-9_+-]+):(?![\p{L}\p{N}])/giu;

// Every known name in the text as its emoji, and an unknown one left alone.
// ⚠️ Not inside backticks: code pasted for a helper is meant character for
// character. And `Object.hasOwn`, or `:constructor:` would find a function.
export function withEmoji(text) {
  return text.split(/(```[\s\S]*?```|`[^`\n]*`)/).map((part, i) => (i % 2 ? part : part.replace(
    NAME,
    (whole, name) => (Object.hasOwn(SHORTCODES, name.toLowerCase()) ? SHORTCODES[name.toLowerCase()] : whole),
  ))).join('');
}
